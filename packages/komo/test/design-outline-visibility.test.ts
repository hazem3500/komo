// @vitest-environment jsdom
import { afterEach, expect, it, vi } from "vitest";
import { createDesignMode } from "../src/design-mode.js";

let controller: ReturnType<typeof createDesignMode>;
afterEach(() => { controller?.destroy(); vi.unstubAllGlobals(); document.body.replaceChildren(); });

it("keeps both decorations suppressed through edits, redraws and comparisons until canvas targeting", async () => {
  document.body.innerHTML = '<main><div id="target" tabindex="0">Target</div><p id="next">Next</p></main><div id="chrome"></div>';
  const target = document.querySelector<HTMLElement>("#target")!;
  const next = document.querySelector<HTMLElement>("#next")!;
  const host = document.querySelector<HTMLElement>("#chrome")!;
  const root = host.attachShadow({ mode: "open" });
  let pointed: Element = target;
  vi.stubGlobal("matchMedia", (query: string) => ({ matches: query.includes("reduced-motion") }));
  let sequence = 0;
  const frames = new Map<number, FrameRequestCallback>();
  vi.stubGlobal("requestAnimationFrame", (callback: FrameRequestCallback) => { frames.set(++sequence, callback); return sequence; });
  vi.stubGlobal("cancelAnimationFrame", (id: number) => frames.delete(id));
  const flush = () => { const batch = [...frames.values()]; frames.clear(); batch.forEach(callback => callback(0)); };
  vi.spyOn(target, "getBoundingClientRect").mockImplementation(() => new DOMRect(20, 30, parseFloat(target.style.width) || 200, 40));
  vi.spyOn(next, "getBoundingClientRect").mockReturnValue(new DOMRect(250, 80, 100, 20));
  controller = createDesignMode({ root, host, targetAt: () => pointed, onComment() {}, onExit() {} });
  controller.setActive(true);
  await controller.ready;
  const move = (element: Element) => { pointed = element; element.dispatchEvent(new MouseEvent("pointermove", { bubbles: true, composed: true })); };
  controller.select(target);
  flush();
  const markers = [...root.querySelectorAll<HTMLElement>(".design-outline")];
  expect(markers[0].hidden).toBe(false);
  move(next);
  expect(markers.every(marker => !marker.hidden)).toBe(true);
  const width = root.querySelector<HTMLInputElement>('[data-property="width"]')!;
  const before = target.getAttribute("style");
  width.focus();
  expect(markers.every(marker => marker.hidden)).toBe(true);
  expect(target.getAttribute("style")).toBe(before);
  width.value = "320";
  width.dispatchEvent(new Event("input", { bubbles: true }));
  width.dispatchEvent(new Event("change", { bubbles: true }));
  flush();
  controller.select(target);
  window.dispatchEvent(new Event("resize"));
  await Promise.resolve();
  flush();
  expect(markers.every(marker => marker.hidden)).toBe(true);
  expect(root.querySelector(".design-inspector__target")!.textContent).toContain("target");
  const sides = root.querySelectorAll<HTMLButtonElement>(".design-inspector__compare button");
  sides[0].click(); flush();
  expect(markers.every(marker => marker.hidden)).toBe(true);
  sides[1].click(); flush();
  expect(markers.every(marker => marker.hidden)).toBe(true);
  move(next);
  expect(markers.every(marker => !marker.hidden)).toBe(true);
  expect(markers[0].style.width).toBe("320px");
  root.querySelector<HTMLButtonElement>('[aria-label="Undo"]')!.click(); flush();
  expect(markers.every(marker => marker.hidden)).toBe(true);
  expect(target.getAttribute("style")).toBe(before);
  move(target);
  expect(markers[0].hidden).toBe(false);
  expect(markers[0].style.width).toBe("200px");
  expect(markers[1].hidden).toBe(true);
});
